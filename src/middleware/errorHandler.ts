import crypto from 'node:crypto';
import type { ErrorRequestHandler, NextFunction, Request, RequestHandler, Response } from 'express';

/**
 * Structured validation or domain sub-error entry attached to RFC 9457 responses.
 */
export interface ValidationIssue {
  /** JSON Pointer (RFC 6901) or parameter path indicating where the error occurred. */
  pointer: string;
  /** Human-readable explanation of the specific field failure. */
  detail: string;
  /** Machine-readable validation rule code. */
  code?: string;
}

/**
 * RFC 9457 Problem Details for HTTP APIs response envelope.
 * @see https://www.rfc-editor.org/rfc/rfc9457
 */
export interface ProblemDetails {
  /** A URI reference that identifies the problem type. */
  type: string;
  /** A short, human-readable summary of the problem type. */
  title: string;
  /** The HTTP status code generated by the origin server for this occurrence. */
  status: number;
  /** A human-readable explanation specific to this occurrence of the problem. */
  detail: string;
  /** A URI reference that identifies the specific occurrence of the problem. */
  instance: string;
  /** Correlation identifier echoed in X-Request-ID for distributed tracing. */
  requestId: string;
  /** ISO-8601 UTC timestamp when the error response was generated. */
  timestamp: string;
  /** Optional structured field-level validation issues. */
  errors?: ValidationIssue[];
}

export interface AppErrorOptions {
  status: number;
  code: string;
  title: string;
  detail: string;
  errors?: ValidationIssue[];
  headers?: Record<string, string>;
  expose?: boolean;
  cause?: unknown;
}

/**
 * Domain & HTTP transport error class designed to map deterministically to RFC 9457.
 */
export class AppError extends Error {
  public readonly status: number;
  public readonly code: string;
  public readonly title: string;
  public readonly detail: string;
  public readonly errors?: ValidationIssue[];
  public readonly headers?: Record<string, string>;
  public readonly expose: boolean;

  constructor(options: AppErrorOptions) {
    super(options.detail, options.cause !== undefined ? { cause: options.cause } : undefined);
    this.name = 'AppError';
    this.status = options.status;
    this.code = options.code;
    this.title = options.title;
    this.detail = options.detail;
    this.errors = options.errors;
    this.headers = options.headers;
    this.expose = options.expose ?? options.status < 500;
    Object.setPrototypeOf(this, new.target.prototype);
  }
}

const SAFE_REQUEST_ID_PATTERN = /^[a-zA-Z0-9._-]{8,128}$/;

/**
 * Assigns or propagates a validated `X-Request-ID` header for end-to-end observability.
 * Rejects malformed or oversized client-supplied IDs to prevent header/log injection.
 */
export const correlationIdMiddleware: RequestHandler = (
  req: Request,
  res: Response,
  next: NextFunction,
): void => {
  const incomingId = req.header('x-request-id');
  const requestId =
    incomingId && SAFE_REQUEST_ID_PATTERN.test(incomingId)
      ? incomingId
      : crypto.randomUUID();

  res.locals.requestId = requestId;
  res.setHeader('X-Request-ID', requestId);
  next();
};

/**
 * Catch-all handler for unmatched routes, emitting a standardized 404 Problem Details error.
 */
export const notFoundHandler: RequestHandler = (
  req: Request,
  _res: Response,
  next: NextFunction,
): void => {
  next(
    new AppError({
      status: 404,
      code: 'resource-not-found',
      title: 'Resource Not Found',
      detail: `No endpoint matches ${req.method} ${req.path}.`,
    }),
  );
};

interface BodyParserError extends Error {
  status?: number;
  statusCode?: number;
  type?: string;
}

function normalizeError(err: unknown): AppError {
  if (err instanceof AppError) {
    return err;
  }

  const candidate = err as BodyParserError | undefined;

  if (candidate?.type === 'entity.too.large' || candidate?.status === 413) {
    return new AppError({
      status: 413,
      code: 'payload-too-large',
      title: 'Content Too Large',
      detail: 'The request payload exceeds the maximum permitted byte size for this endpoint.',
      cause: err,
    });
  }

  if (err instanceof SyntaxError && (candidate?.status === 400 || candidate?.statusCode === 400)) {
    return new AppError({
      status: 400,
      code: 'malformed-json',
      title: 'Malformed JSON Payload',
      detail: 'The request body could not be parsed as valid RFC 8259 JSON.',
      cause: err,
    });
  }

  return new AppError({
    status: 500,
    code: 'internal-server-error',
    title: 'Internal Server Error',
    detail: 'An unexpected internal error occurred while processing the request.',
    expose: false,
    cause: err,
  });
}

export interface ErrorHandlerConfig {
  /** Base URI used to construct RFC 9457 `type` identifiers. */
  problemBaseUri?: string;
  /** Environment name; stack traces and non-exposed details are suppressed in `production`. */
  environment?: string;
  /** Optional custom logger sink (defaults to structured JSON on console.error). */
  logger?: (entry: Record<string, unknown>) => void;
}

/**
 * Factory producing a centralized RFC 9457 (`application/problem+json`) error handler.
 * Never leaks internal stack traces or database error strings in production responses.
 */
export function createErrorHandler(config: ErrorHandlerConfig = {}): ErrorRequestHandler {
  const baseUri = (
    config.problemBaseUri ??
    process.env.PROBLEM_BASE_URI ??
    'https://api.cynbit.com/problems'
  ).replace(/\/+$/, '');
  const env = config.environment ?? process.env.NODE_ENV ?? 'development';
  const isProduction = env === 'production';
  const log =
    config.logger ??
    ((entry: Record<string, unknown>) => {
      if (env !== 'test') {
        console.error(JSON.stringify(entry));
      }
    });

  return (err: unknown, req: Request, res: Response, _next: NextFunction): void => {
    const requestId =
      typeof res.locals.requestId === 'string' ? res.locals.requestId : crypto.randomUUID();
    const appError = normalizeError(err);

    const logEntry: Record<string, unknown> = {
      level: appError.status >= 500 ? 'error' : 'warn',
      timestamp: new Date().toISOString(),
      requestId,
      method: req.method,
      path: req.originalUrl,
      status: appError.status,
      code: appError.code,
      message: err instanceof Error ? err.message : String(err),
    };

    if (err instanceof Error && err.stack && appError.status >= 500) {
      logEntry.stack = err.stack;
    }

    log(logEntry);

    if (res.headersSent) {
      return;
    }

    if (appError.headers) {
      for (const [headerName, headerValue] of Object.entries(appError.headers)) {
        res.setHeader(headerName, headerValue);
      }
    }

    const safeDetail =
      appError.expose || !isProduction
        ? appError.detail
        : 'An unexpected error occurred. Reference the requestId when contacting support.';

    const problem: ProblemDetails = {
      type: `${baseUri}/${appError.code}`,
      title: appError.title,
      status: appError.status,
      detail: safeDetail,
      instance: req.originalUrl,
      requestId,
      timestamp: new Date().toISOString(),
      ...(appError.errors && appError.errors.length > 0 ? { errors: appError.errors } : {}),
    };

    res
      .status(appError.status)
      .setHeader('X-Request-ID', requestId)
      .setHeader('Cache-Control', 'no-store')
      .setHeader('Content-Type', 'application/problem+json; charset=utf-8')
      .send(JSON.stringify(problem));
  };
}
